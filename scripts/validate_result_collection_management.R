entries <- lapply(1:3, function(i) list(id = paste0("item", i), title = paste0("Result ", i),
  saved_at = "2026-09-13", html = paste0("<p>Complete result ", i, "</p>")))
ids <- function(x) vapply(x, `[[`, character(1), "id")
stopifnot(identical(ids(result_collection_edit(entries, "item2", "up")), c("item2", "item1", "item3")))
stopifnot(identical(result_collection_edit(entries, "missing", "delete"), entries))
stopifnot(identical(result_collection_edit(entries, "item1", "up"), entries))
stopifnot(length(result_collection_edit(entries, "item2", "delete")) == 2L)
stopifnot(length(unique(ids(normalize_result_snapshot_entries(c(entries, entries))))) == 6L)
shiny::testServer(function(input, output, session) {
  language <- reactiveVal("ko")
  store <- result_accumulator_store(session)
  store(entries)
  register_result_accumulator_outputs(input, output, session, app_language_fn = language)
}, {
  session$flushReact()
  stopifnot(grepl("HWPX", output$result_export_controls$html, fixed = TRUE))
  language("en"); session$flushReact()
  stopifnot(!grepl("HWPX", output$result_export_controls$html, fixed = TRUE))
  session$setInputs(saved_result_entry_action = list(id = "item2", action = "down"))
  stopifnot(identical(ids(store()), c("item1", "item3", "item2")))
  stopifnot(identical(ids(read_result_snapshot_store()), ids(store())))
  session$setInputs(saved_result_entry_action = list(id = "item3", action = "delete"))
  stopifnot(identical(ids(store()), c("item1", "item2")))
  session$setInputs(undo_saved_result_edit = 1)
  stopifnot(identical(ids(store()), c("item1", "item3", "item2")))
  session$setInputs(saved_result_entry_action = list(id = "item1", action = "delete"))
  new_entry <- list(id = "new", title = "New result", saved_at = "today", html = "<p>New content</p>")
  store(c(store(), list(new_entry))); session$flushReact()
  session$setInputs(undo_saved_result_edit = 2)
  stopifnot("new" %in% ids(store()), !"item1" %in% ids(store()))
  store(list(entries[[1]])); session$flushReact()
  session$setInputs(saved_result_entry_action = list(id = "item1", action = "delete"))
  stopifnot(length(store()) == 0L, grepl("undo_saved_result_edit", output$saved_results_list$html, fixed = TRUE))
  session$setInputs(undo_saved_result_edit = 3)
  stopifnot(identical(store(), list(entries[[1]])))
})
