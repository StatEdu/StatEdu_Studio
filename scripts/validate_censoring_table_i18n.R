Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
out<-'tmp/censoring-table-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE);entries<-list()
status<-c(rep(1,4),rep(0,2),rep(1,2),rep(0,6),rep(2,6))
groups<-c(rep('Review',4),rep('사용자 <&> %s',4),rep('All analysis records',12))
for(kind in c('pooled','stratified'))for(language in c('en','ko','ja','zh','es','fr','de','vi')){
 raw<-survival_censoring_group_table(status,if(kind=='pooled')NULL else groups)
 r<-list(censoring_group_table=raw,censoring_group=if(kind=='pooled')'' else '변수 <&> %s')
 rows<-survival_censoring_group_display_table(r,language)
 html<-as.character(tagList(tags$h4(survival_appendix_title('Censoring-distribution estimation',language)),survival_simple_table(rows,table_language=language),survival_censoring_group_note(r,language)))
 doc<-xml2::read_html(html,encoding='UTF-8')
 if(kind=='stratified')stopifnot(identical(trimws(xml2::xml_text(xml2::xml_find_all(doc,'//tbody/tr/td[1]'))),raw[[1]]),grepl(r$censoring_group,xml2::xml_text(doc),fixed=TRUE))
 values<-xml2::xml_text(xml2::xml_find_all(doc,'//tbody/tr/td[position()>=2 and position()<=6]'))
 if(language=='en')baseline<-values else stopifnot(identical(values,baseline),!grepl('Censoring-distribution estimation|Fewer than 10 analysis records|No censored observations|Fewer than 5 censored observations|The censoring distribution was estimated|One censoring distribution was estimated',xml2::xml_text(doc)))
 stopifnot(identical(trimws(xml2::xml_text(xml2::xml_find_all(doc,'//tbody/tr/td[7]'))),rows[[7]]))
 if(language=='ja')entries[[kind]]<-list(id=kind,title=kind,html=html)
 cat('PASS:',kind,language,'censoring reasons, user strata, counts and notes\n')
}
saveRDS(unname(entries),file.path(out,'entries.rds'))
