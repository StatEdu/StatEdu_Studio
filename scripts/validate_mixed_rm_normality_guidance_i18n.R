Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
set.seed(918)
n<-40; subject<-c(rnorm(n-2),-25,30)
d<-data.frame(group=rep(c('Review','Normality'),each=n/2),pre=subject+rnorm(n,0,.1),post=subject+rnorm(n,0,.2),last=subject+rnorm(n,0,.3))
info<-data.frame(name=names(d),measurement=c('category',rep('continuous',3)))
r<-prepare_mixed_rm_anova_results(d,group_variable='group',repeated_variables=c('pre','post','last'),variable_info=info,options=list(assumption_check=TRUE,posthoc=FALSE))
phrases<-c('At least one Shapiro-Wilk p < .05; treat this as a sensitivity-analysis cue.','Normality flagged; review LMM/robust sensitivity if distributional mismatch is meaningful.','Consider LMM with robust/bootstrap inference as a sensitivity analysis.')
stopifnot(mixed_rm_normality_issue(r$normality),all(vapply(phrases,function(p)any(grepl(p,unlist(r$recommendation),fixed=TRUE)),logical(1))))
before<-serialize(r,NULL);captured<-list();failures<-character()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang)
 expected<-vapply(phrases,function(p)if(lang=='ko')mixed_rm_appendix_korean_text(p)else result_appendix_ui_text(p,lang),character(1))
 if(lang!='en'&&any(expected==phrases))failures<-c(failures,paste(lang,'catalog'))
 html<-as.character(mixed_rm_anova_results_ui(r));doc<-xml2::read_html(html)
 cells<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//td"))
 if(!all(vapply(expected,function(p)any(grepl(p,cells,fixed=TRUE)),logical(1))))failures<-c(failures,paste(lang,'render'))
 main<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main)>0)
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(r,NULL)))
 probe<-mixed_rm_appendix_table(data.frame(Variable=phrases,Group=c('Review','Normality','Unknown'),Reason=phrases))
 stopifnot(identical(probe[[1]],phrases),identical(probe[[2]],c('Review','Normality','Unknown')))
 captured[[lang]]<-html
}
if(length(failures))stop(paste('Normality guidance failures:',paste(failures,collapse=', ')))
out<-'tmp/mixed-rm-normality-guidance-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual mixed RM normality guidance including combined reason in eight languages; main/source/user labels preserved\n')
