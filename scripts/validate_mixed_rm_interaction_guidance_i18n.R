Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
set.seed(7);n<-80;z<-rep(seq(-2,2,length.out=40),2)
d<-data.frame(group=rep(c('Review','Normality'),each=40),factor2=rep(c('Unknown','Result'),40),z=z,pre=10+rnorm(n,0,.15),post=10+z+rnorm(n,0,.15),last=10+2*z+rnorm(n,0,.15))
info<-data.frame(name=names(d),measurement=c('category','category',rep('continuous',4)))
r<-prepare_mixed_rm_anova_results(d,group_variable=c('group','factor2'),repeated_variables=c('pre','post','last'),covariates='z',variable_info=info,options=list(assumption_check=FALSE,posthoc=FALSE))
phrases<-c('Covariate effects vary over time; interpret adjusted means and Time effects with caution.','More than one independent variable was selected, so between-subject main effects and their interactions are modeled.')
stopifnot(any(r$anova$Effect=='z x Time' & r$anova$p=='<.001'),all(phrases%in%unlist(r$recommendation)))
before<-serialize(r,NULL);captured<-list();failures<-character()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang)
 expected<-vapply(phrases,function(p)if(lang=='ko')mixed_rm_appendix_korean_text(p)else result_appendix_ui_text(p,lang),character(1))
 if(lang!='en'&&any(expected==phrases))failures<-c(failures,paste(lang,'catalog'))
 html<-as.character(mixed_rm_anova_results_ui(r));doc<-xml2::read_html(html)
 cells<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//td"))
 stopifnot(all(expected%in%cells))
 main<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main)>0)
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(r,NULL)))
 probe<-mixed_rm_appendix_table(data.frame(Variable=phrases,Group=c('Review','Normality'),Reason=phrases))
 stopifnot(identical(probe[[1]],phrases),identical(probe[[2]],c('Review','Normality')))
 captured[[lang]]<-html
}
if(length(failures))stop(paste('Interaction guidance failures:',paste(failures,collapse=', ')))
out<-'tmp/mixed-rm-interaction-guidance-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual factorial RM ANCOVA guidance in eight languages; main/source/user labels preserved\n')
