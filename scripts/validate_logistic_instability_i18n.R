Sys.setlocale("LC_CTYPE","English_United States.utf8")
Sys.setenv(STATEDU_MODULE_CACHE="false")
source("R/app_bootstrap.R",encoding="UTF-8")
load_app_packages(check=FALSE); source_app_modules()
d <- data.frame(x=rep(c(-1,1),each=30),y=factor(rep(0:1,each=30)))
info <- data.frame(name=c("x","y"),measurement=c("continuous","binary"))
results <- prepare_logistic_analysis_results(d,"y","x",variable_info=info)
stopifnot(length(results)==1L)
notes <- logistic_result_notes(results[[1]])
instability <- logistic_instability_note(results[[1]])
separation <- notes[startsWith(notes,"Complete or quasi-complete separation")]
stopifnot(nzchar(instability),length(separation)==1L)
messages <- c(logistic_instability_summary(notes),separation,instability)
out <- "tmp/logistic-instability-i18n";dir.create(out,recursive=TRUE,showWarnings=FALSE)
baseline <- NULL
for(language in c("en","ko","ja","zh","es","fr","de","vi")) {
 options(statedu.app_language=language)
 probe <- logistic_appendix_table(data.frame(Variable=messages,Message=messages),language)
 stopifnot(identical(probe[[1]],messages))
 if(language!="en") stopifnot(all(probe[[2]]!=messages))
 html <- as.character(htmltools::renderTags(logistic_results_panel(results,info))$html)
 doc <- xml2::read_html(html,encoding="UTF-8")
 main <- xml2::xml_find_all(doc,"//table[@data-result-table-role='main']")
 content <- lapply(main,function(t) list(cells=xml2::xml_text(xml2::xml_find_all(t,".//th|.//td")),notes=xml2::xml_text(xml2::xml_find_all(t,"ancestor::div[@data-result-table-sheet='true'][1]/*[not(self::table)]"))))
 stopifnot(length(main)>0L,all(xml2::xml_attr(main,"data-result-table-language")=="en"))
 if(language=="en") baseline<-content else stopifnot(identical(content,baseline))
 appendix <- paste(xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']")),collapse="\n")
 if(language!="en") for(message in messages) stopifnot(!grepl(message,appendix,fixed=TRUE))
 if(language=="ja") saveRDS(list(list(id="logistic-instability",title="Logistic diagnostics",html=paste0(html,as.character(analysis_result_table_section("不安定なモデル",probe))))),file.path(out,"entries.rds"))
 cat("PASS:",language,"actual separated binary fit; instability translations; English main tables and user text preserved\n")
}
