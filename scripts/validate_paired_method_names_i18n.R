Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
d<-data.frame(Review=1:5,Normality=c(2,3,5,7,11),binary1=c('yes','yes','no','no','yes'),binary2=c('yes','no','no','yes','no'))
info<-data.frame(name=names(d),measurement=c('continuous','continuous','binary','binary'))
r<-prepare_paired_results(d,c('Review','binary1'),c('Normality','binary2'),info,options=list(assumption_check=FALSE,effect_size=TRUE))
stopifnot(all(c('Paired t-test','Exact McNemar test')%in%r$table$Method))
phrases<-c('paired t','Paired t-test','Exact McNemar','Exact McNemar test')
before<-serialize(r,NULL);captured<-list();missing<-character()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang)
 labels<-vapply(phrases,paired_appendix_text,character(1),language=lang)
 if(lang!='en'&&any(labels==phrases))missing<-c(missing,lang)
 html<-as.character(paired_results_ui(r));doc<-xml2::read_html(html)
 cells<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//td"))
 stopifnot(all(labels[c(1,3)]%in%cells),'Review - Normality'%in%cells)
 long<-paired_appendix_table(data.frame(Method=phrases[c(2,4)]))
 stopifnot(identical(unname(as.character(long[[1]])),unname(labels[c(2,4)])))
 main<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main)>0)
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(r,NULL)))
 captured[[lang]]<-html
}
if(length(missing))stop(paste('Untranslated paired method names:',paste(missing,collapse=', ')))
out<-'tmp/paired-method-names-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual paired t / exact McNemar overview and long labels in eight languages; main tables/source preserved\n')
