Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
out<-'tmp/cox-spline-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE);entries<-list()
d<-read.csv('scripts/fixtures/survival_validation.csv')
lines<-readLines('R/result_survival_ui.R',encoding='UTF-8')
note<-sub('",?\\s*$','',sub('^\\s*"','',lines[grepl('^\\s*"The likelihood-ratio test compares the prespecified natural-cubic-spline',lines)]))
stopifnot(length(note)==1)
for(spline_df in c(3L,4L)){
 result<-prepare_cox_analysis_result(d,'time','status',c('age','sex'),event_value='1',spline_covariate='age',spline_df=spline_df)
 stopifnot(nrow(result$spline_test_table)==1,nrow(result$spline_curve)>0)
 for(language in c('en','ko','ja','zh','es','fr','de','vi')){
  options(statedu.app_language=language);rows<-survival_cox_spline_test_display_table(result)
  title<-survival_appendix_title('Natural cubic spline functional-form analysis',language)
  table<-survival_simple_table(rows,table_language=language)
  doc<-xml2::read_html(as.character(table),encoding='UTF-8')
  values<-xml2::xml_text(xml2::xml_find_all(doc,'//td'))
  if(language=='en')baseline<-values else stopifnot(identical(values,baseline),!any(names(rows)[c(2,3,4,7,8)]%in%xml2::xml_text(xml2::xml_find_all(doc,'//th'))))
  custom<-rows;custom$Variable<-'Review 사용자 <&> %s'
  custom_doc<-xml2::read_html(as.character(survival_simple_table(custom,table_language=language)),encoding='UTF-8')
  stopifnot(identical(trimws(xml2::xml_text(xml2::xml_find_all(custom_doc,'//tbody/tr/td[1]'))),custom$Variable))
  full<-xml2::read_html(as.character(survival_cox_results_panel(result,language)),encoding='UTF-8')
  stopifnot(title%in%xml2::xml_text(xml2::xml_find_all(full,'//h4')))
  if(language!='en')stopifnot(title!='Natural cubic spline functional-form analysis',!grepl(substr(note,1,60),xml2::xml_text(full),fixed=TRUE))
  if(language%in%c('ja','zh','es','fr','de','vi'))stopifnot(grepl(substr(statedu_localized_text(language,note),1,30),xml2::xml_text(full),fixed=TRUE))
  main<-xml2::xml_text(xml2::xml_find_all(xml2::read_html(as.character(survival_cox_result_html_table(result,language)),encoding='UTF-8'),'//th|//td'))
  if(language=='en')main_baseline<-main else stopifnot(identical(main,main_baseline))
  if(language=='ja')entries[[as.character(spline_df)]]<-list(id=paste0('df',spline_df),title=paste0('df',spline_df),html=as.character(tagList(tags$h4(title),table,survival_simple_table(custom,table_language=language),survival_table_note(statedu_localized_text(language,note)))))
  cat('PASS: df',spline_df,language,'actual spline, headers, note, values and English main table\n')
 }
}
saveRDS(unname(entries),file.path(out,'entries.rds'))
