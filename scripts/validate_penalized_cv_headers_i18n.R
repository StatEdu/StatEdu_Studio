Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
set.seed(930);d<-data.frame(x=rnorm(60),z=rnorm(60));d$y<-2*d$x-d$z+rnorm(60)
info<-data.frame(name=names(d),measurement='continuous')
r<-prepare_penalized_menu(d,'y',c('x','z'),'LASSO',info,resamples=2,seed=12,validation_repeats=1)
phrases<-c('CV folds','CV MSE','CV SE','CV RMSE','CV MAE','CV R²','Apparent R²','N complete')
ko<-c('교차검증 폴드','교차검증 MSE','교차검증 표준오차','교차검증 RMSE','교차검증 MAE','교차검증 R²','표본내 R²','완전 사례 수')
stopifnot(all(phrases%in%names(r$summary)))
before<-serialize(r,NULL);captured<-list();failures<-character()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang)
 expected<-if(lang=='ko')ko else vapply(phrases,result_appendix_ui_text,character(1),language=lang)
 if(lang!='en'&&any(expected==phrases))failures<-c(failures,paste(lang,'catalog'))
 html<-as.character(htmltools::renderTags(penalized_result_block(r))$html);doc<-xml2::read_html(html)
 headers<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//th"));stopifnot(all(expected%in%headers))
 main<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main)>0)
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(r,NULL)))
 captured[[lang]]<-html
}
if(length(failures))stop(paste('CV header failures:',paste(failures,collapse=', ')))
out<-'tmp/penalized-cv-headers-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual LASSO CV appendix headers across eight languages; main/source preserved\n')
