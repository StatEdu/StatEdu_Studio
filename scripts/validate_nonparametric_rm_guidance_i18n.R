Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
d<-data.frame(Review=c(1,2,3,4,5,6),Normality=c(2,4,3,5,7,6),third=c(3,2,5,6,8,7))
b<-data.frame(Review=c('no','yes','no','yes','no','yes'),Normality=c('yes','yes','no','no','yes','yes'),third=c('yes','no','yes','yes','no','yes'))
levels<-c('continuous','ordinal','binary')
results<-lapply(levels,function(level){data<-if(level=='binary')b else d;prepare_nonparametric_paired_rm_results(data,list(names(data)),data.frame(name=names(data),measurement=level))})
stopifnot(identical(vapply(results,function(r)r$measurement,character(1)),c('Continuous','Ordinal','Binary')))
before<-serialize(results,NULL);records<-list();captured<-list()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang);main<-list();panels<-list()
 for(i in seq_along(results)) {
  r<-results[[i]];measurement<-paired_appendix_text(r$measurement,lang)
  expected<-sprintf(statedu_localized_text(lang,'%s nonparametric repeated-measures test','%s 비모수 반복측정 검정'),measurement)
  if(lang!='en')stopifnot(!grepl('nonparametric repeated-measures test',expected,fixed=TRUE))
  panels[[i]]<-as.character(nonparametric_paired_results_ui(r))
  doc<-xml2::read_html(panels[[i]])
  cells<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//td"))
  stopifnot(expected%in%cells,any(grepl('Review',cells,fixed=TRUE)),any(grepl('Normality',cells,fixed=TRUE)))
  main[[i]]<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main[[i]])>0)
  records[[length(records)+1L]]<-data.frame(language=lang,measurement=r$measurement,display=expected)
 }
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(results,NULL)))
 captured[[lang]]<-paste(unlist(panels),collapse='\n')
}
out<-'tmp/nonparametric-rm-guidance-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
write.csv(do.call(rbind,records),file.path(out,'guidance.csv'),row.names=FALSE,fileEncoding='UTF-8')
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual continuous/ordinal/binary guidance in eight languages; displayed descriptions, user names, English main tables and source preserved\n')
