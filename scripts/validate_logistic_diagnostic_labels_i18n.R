Sys.setlocale('LC_CTYPE','English_United States.utf8');Sys.setenv(STATEDU_MODULE_CACHE='false')
source('R/app_bootstrap.R',encoding='UTF-8');load_app_packages(check=FALSE);source_app_modules()
d<-data.frame(x=factor(rep(c('Review','Normality'),each=4)),y=factor(rep(0:1,each=4)))
info<-data.frame(name=c('x','y'),measurement=c('category','binary'))
results<-prepare_logistic_analysis_results(d,'y','x',variable_info=info)
phrases<-c('Convergence','EPV / sparse','Separation','EPV/sparse warning','Separation warning')
overview<-logistic_model_overview_data_frame(results,info)
stopifnot(all(vapply(phrases[4:5],function(p)any(grepl(p,unlist(overview),fixed=TRUE)),logical(1))))
before<-serialize(results,NULL);captured<-list();failures<-character()
for(lang in c('en','ko','ja','zh','es','fr','de','vi')) {
 options(statedu.app_language=lang)
 expected<-vapply(phrases,logistic_appendix_text,character(1),language=lang)
 # French Convergence and German Separation legitimately match English spelling.
 same_allowed<-if(lang=='fr')1L else if(lang=='de')3L else integer()
 if(lang!='en'&&any((expected==phrases)[setdiff(seq_along(phrases),same_allowed)]))failures<-c(failures,paste(lang,'catalog'))
 html<-as.character(htmltools::renderTags(logistic_results_panel(results,info))$html);doc<-xml2::read_html(html)
 cells<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='appendix']//td"))
 if(!all(vapply(expected,function(p)any(grepl(p,cells,fixed=TRUE)),logical(1))))failures<-c(failures,paste(lang,'render'))
 if(lang!='en'&&any(grepl('EPV/sparse warning|Separation warning',cells)))failures<-c(failures,paste(lang,'English residue'))
 main<-xml2::xml_text(xml2::xml_find_all(doc,"//table[@data-result-table-role='main']"));stopifnot(length(main)>0)
 if(lang=='en')baseline<-main else stopifnot(identical(main,baseline))
 stopifnot(identical(before,serialize(results,NULL)))
 probe<-logistic_appendix_table(data.frame(Variable=phrases,Message=phrases),lang);stopifnot(identical(probe[[1]],phrases))
 captured[[lang]]<-html
}
if(length(failures))stop(paste('Diagnostic label failures:',paste(failures,collapse=', ')))
out<-'tmp/logistic-diagnostic-labels-i18n';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(captured,file.path(out,'captured.json'),auto_unbox=TRUE)
cat('PASS actual sparse separated binary fit diagnostic labels in eight languages; main/source/user labels preserved\n')
